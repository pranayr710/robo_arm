/** Strokes for a character, points normalised to x 0..1 (of glyph width) and
 *  y 0..1 (of letter height). Returns null for unknown chars (incl. space). */
export function strokesFor(ch) {
  const g = G[String(ch).toUpperCase()];
  if (!g) return null;
  return g.map((stroke) => stroke.map(([x, y]) => [x / 4, y / 6]));
}
